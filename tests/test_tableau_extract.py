def test_corridor_spread_daily_reproduces_lasalgaon_mumbai_inversion():
    """Verify Dataset B reproduces the 507-day Lasalgaon-Mumbai inversion case study."""
    csv_path = TABLEAU_DIR / "corridor_spread_daily.csv"
    assert csv_path.exists()
    df = pd.read_csv(csv_path)

    # Filter for Lasalgaon -> Mumbai corridor
    las_mum = df[df["corridor_id"] == "CORR_LAS_MUM_ONION"]
    assert len(las_mum) == 507, f"Expected 507 matched days, found {len(las_mum)}"

    # Check price spread metrics
    mean_spread = round(float(las_mum["price_spread_quintal"].mean()), 2)
    assert mean_spread == -157.76, f"Mean spread mismatch: {mean_spread}"

    neg_spread_count = (las_mum["price_spread_quintal"] < 0).sum()
    neg_spread_pct = round(neg_spread_count / len(las_mum) * 100.0, 2)
    assert neg_spread_pct == 74.75, f"Negative spread % mismatch: {neg_spread_pct}"

    # Check variety confounding indicator (260 cultivar-confounded days vs 247 generic-matched days)
    status_counts = las_mum["variety_comparability_status"].value_counts().to_dict()
    assert status_counts.get("CULTIVAR_CONFOUNDED_OTHER") == 260
    assert status_counts.get("GENERIC_TIER_MATCHED") == 247


